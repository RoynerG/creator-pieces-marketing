const fold = (text) =>
  text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
// Accent-insensitive, with names that start with the query listed first.
export function searchBarrios(query) {
  const text = fold(query.trim());
  const matches = [...MAIN_BARRIOS, ...OTHER_BARRIOS].filter((name) =>
    fold(name).includes(text),
  );
  return [
    ...matches.filter((name) => fold(name).startsWith(text)),
    ...matches.filter((name) => !fold(name).startsWith(text)),
  ];
}
